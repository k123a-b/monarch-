const byName = new Map(media.map((entry) => [entry.name, entry]));
export const ukCards = [
  ...celebrities.map((entry) => ["celebrity", ...entry]),
  ...locations.map((entry) => ["location", ...entry]),
].map(([kind, name, rarity, value], index) => {
  const source = byName.get(name);
  if (!source?.image || !source?.page) throw Error(`Missing UK artwork: ${name}`);
  return {
    id: `uk-${kind}-${name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/-$/, "")}`,
    name,
    set: "uk",
    kind,
    country: "United Kingdom",
    role: source.subtitle,
    rarity,
    value,
    image: source.image,
    page: source.page,
    imageSource: source.imageSource,
    imageCredit: source.imageCredit,
    imageLicense: source.imageLicense,
    imageLicenseUrl: source.imageLicenseUrl,
    pattern: ["rays", "grid", "stars", "waves"][index % 4],
    colors: rarity === "Crown" || rarity === "Chase"
      ? ["#49371e", "#e2c685"]
      : ["#20324f", "#91b9d6"],
    flavor: kind === "celebrity"
      ? "A familiar face in the UK collection. All rarity and value ratings are fictional."
      : "A landmark from across the United Kingdom. A place to keep in your collection.",
  };
});
